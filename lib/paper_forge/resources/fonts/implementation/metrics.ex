  @doc """
  Returns the width of one codepoint in one-thousandth-em units.
  """
  @spec width(Builtin.font_key(), non_neg_integer()) ::
          non_neg_integer()
  def width(font_key, codepoint)
      when is_integer(codepoint) and codepoint >= 0 do
    definition =
      Builtin.fetch!(font_key)

    normalized_codepoint =
      normalize_codepoint(codepoint)

    width_for(
      definition.family,
      definition.style,
      normalized_codepoint
    )
  end

  defp width_for(:courier, _style, ?\t) do
    600 * 4
  end

  defp width_for(:courier, _style, _codepoint) do
    600
  end

  defp width_for(:helvetica, style, codepoint)
       when style in [:bold, :bold_italic] do
    metric(@helvetica_bold, codepoint, 556)
  end

  defp width_for(:helvetica, _style, codepoint) do
    metric(@helvetica, codepoint, 556)
  end

  defp width_for(:times, style, codepoint)
       when style in [:bold, :bold_italic] do
    metric(@times_bold, codepoint, 500)
  end

  defp width_for(:times, _style, codepoint) do
    metric(@times, codepoint, 500)
  end

  defp width_for(:symbol, _style, codepoint) do
    metric(@helvetica, codepoint, 600)
  end

  defp width_for(:zapf_dingbats, _style, codepoint) do
    metric(@helvetica, codepoint, 600)
  end

  defp metric(metrics, ?\t, _fallback) do
    Map.fetch!(metrics, 32) * 4
  end

  defp metric(metrics, codepoint, fallback) do
    Map.get(
      metrics,
      codepoint,
      fallback
    )
  end

  defp normalize_codepoint(codepoint) do
    Map.get(
      @accent_aliases,
      codepoint,
      codepoint
    )
  end
